/* 월급수비대: only the public app shell is cached here. User data stays in
   the application's account-scoped storage; /api is always a network request. */
const CACHE = 'salary-guardians-shell-v1';
const PREFIX = 'salary-guardians-shell-';
const ROUTES = new Set(['#home', '#expenses', '#loan', '#savings', '#missions', '#stats', '#settings']);
const CORE = ['/manifest.webmanifest', '/icons/icon-192.png', '/icons/icon-512.png', '/icons/apple-touch-icon.png'];

function safeLink(value) {
  try {
    const url = new URL(typeof value === 'string' ? value : '/#home', self.location.origin);
    if (url.origin !== self.location.origin || !['/', '/index.html'].includes(url.pathname)) return '/#home';
    return '/' + (ROUTES.has(url.hash) ? url.hash : '#home');
  } catch {
    return '/#home';
  }
}

function publicAsset(url) {
  return url.origin === self.location.origin &&
    (url.pathname.startsWith('/assets/') && url.pathname !== '/assets/pixel-art-concept.png' ||
     url.pathname.startsWith('/icons/') || url.pathname === '/manifest.webmanifest');
}

async function cacheShell(cache, response) {
  await cache.put('/', response.clone());
  const html = await response.text();
  const refs = [...html.matchAll(/(?:src|href)=["']([^"']+)["']/g)]
    .map(match => new URL(match[1], self.location.origin))
    .filter(url => publicAsset(url) && /\.(?:js|css)$/.test(url.pathname));
  await Promise.allSettled(refs.map(async url => {
    const asset = await fetch(url.href, { cache: 'reload', credentials: 'same-origin' });
    if (asset.ok) await cache.put(url.href, asset);
  }));
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const shell = await fetch('/', { cache: 'reload', credentials: 'same-origin' });
    if (!shell.ok) throw new Error('The app shell is unavailable.');
    await cacheShell(cache, shell);
    await Promise.allSettled(CORE.map(async path => {
      const response = await fetch(path, { cache: 'reload', credentials: 'same-origin' });
      if (response.ok) await cache.put(path, response);
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key.startsWith(PREFIX) && key !== CACHE).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin ||
      url.pathname === '/api' || url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      try {
        const response = await fetch(request);
        if (response.ok && response.headers.get('content-type')?.includes('text/html')) {
          // Refresh the shell and its immutable, build-hashed JS/CSS together.
          event.waitUntil(cacheShell(cache, response.clone()));
        }
        return response;
      } catch {
        return await cache.match('/') || new Response('인터넷 연결 후 월급수비대를 다시 열어 주세요.', {
          status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' }
        });
      }
    })());
  } else if (publicAsset(url)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(request);
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok && response.type !== 'opaque') await cache.put(request, response.clone());
      return response;
    })());
  }
});

self.addEventListener('push', event => {
  let payload = {};
  try { payload = event.data?.json() || {}; } catch { /* A malformed push still displays a safe notification. */ }
  const text = (value, fallback, length) => typeof value === 'string' && value.trim() ? value.trim().slice(0, length) : fallback;
  const title = text(payload.title, '월급수비대', 80);
  const body = text(payload.body, '새로운 수비 미션이 도착했어요. 앱에서 확인해 주세요.', 180);
  event.waitUntil(self.registration.showNotification(title, {
    body,
    icon: '/icons/icon-192.png',
    badge: '/icons/badge-96.png',
    tag: text(payload.tag, 'salary-guardians', 160),
    renotify: false,
    data: { url: safeLink(payload.url) },
    // Payloads are generated by our server with generic text only. Amounts,
    // transaction notes, email addresses and balances must never be included.
  }));
});

self.addEventListener('notificationclick', event => {
  event.notification.close();
  const path = safeLink(event.notification.data?.url);
  const target = new URL(path, self.location.origin).href;
  event.waitUntil((async () => {
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of windows) {
      if (new URL(client.url).origin !== self.location.origin) continue;
      try {
        await client.navigate(target);
        await client.focus();
        return;
      } catch { /* A closing window may no longer be navigable. */ }
    }
    await self.clients.openWindow(target);
  })());
});
