export function Pixel({ kind, size = 84, className }: PixelProps) {
  const name: PixelKind = Object.prototype.hasOwnProperty.call(sprites, kind) ? kind as PixelKind : 'captain';
  const rows = sprites[name];
  return (
    <svg className={`pixel-character ${className || ''}`} width={size} height={size * 1.1} viewBox="0 0 40 44"
      xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false"
      shapeRendering="crispEdges" style={{ overflow: 'visible', imageRendering: 'pixelated', flexShrink: 0 }}>
      {rows.flatMap((row, y) => {
        const cells = [];
        for (let x = 0; x < row.length;) {
          const color = row[x];
          let end = x + 1;
          while (end < row.length && row[end] === color) end++;
          if (color !== '.') cells.push(<rect key={`${y}-${x}`} x={x} y={y} width={end - x} height="1" fill={palette[color]} />);
          x = end;
        }
        return cells;
      })}
    </svg>
  );
}

export default Pixel;
